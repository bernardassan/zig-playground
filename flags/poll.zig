test "Poll - check individual event flags" {
    const value: u32 = Epoll.IN | Epoll.ERR;
    const events: Epoll = @bitCast(value);

    // Check which events occurred
    if (events.err) {
        // Handle error
        try testing.expect(true);
    }
    if (events.in) {
        // Handle readable
        try testing.expect(true);
    }
    if (events.out) {
        // This shouldn't happen
        try testing.expect(false);
    }
}

